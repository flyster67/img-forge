use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result};
use serde::Serialize;

use crate::pipeline::{Format, ProcessConfig, ProcessedAsset};

#[derive(Serialize)]
struct ManifestFile {
    file: String,
    width: u32,
    format: &'static str,
    bytes: u64,
}

#[derive(Serialize)]
struct ManifestEntry {
    source: String,
    original_bytes: u64,
    outputs: Vec<ManifestFile>,
}

fn rel_path_str(path: &Path, base: &Path) -> String {
    path.strip_prefix(base)
        .unwrap_or(path)
        .to_str()
        .unwrap_or_default()
        .replace('\\', "/")
}

fn encode_url_path(path: &str) -> String {
    let mut encoded = String::with_capacity(path.len());
    for b in path.bytes() {
        match b {
            b' ' => encoded.push_str("%20"),
            b'"' => encoded.push_str("%22"),
            b'<' => encoded.push_str("%3C"),
            b'>' => encoded.push_str("%3E"),
            b'#' => encoded.push_str("%23"),
            _ => encoded.push(b as char),
        }
    }
    encoded
}

fn escape_html(input: &str) -> String {
    let mut escaped = String::with_capacity(input.len());
    for c in input.chars() {
        match c {
            '&' => escaped.push_str("&amp;"),
            '<' => escaped.push_str("&lt;"),
            '>' => escaped.push_str("&gt;"),
            '"' => escaped.push_str("&quot;"),
            '\'' => escaped.push_str("&#39;"),
            _ => escaped.push(c),
        }
    }
    escaped
}

pub fn write_outputs(
    cfg: &ProcessConfig,
    assets: &[ProcessedAsset],
    emit_html: bool,
    emit_manifest: bool,
) -> Result<()> {
    if !emit_html && !emit_manifest {
        return Ok(());
    }
    fs::create_dir_all(&cfg.output_dir).with_context(|| format!("create {}", cfg.output_dir.display()))?;

    let mut sorted: Vec<&ProcessedAsset> = assets.iter().collect();
    sorted.sort_by(|a, b| a.original.cmp(&b.original));

    if emit_html {
        let mut html = String::from("<!-- Generated by img-forge -->\n");
        for asset in &sorted {
            let alt = asset
                .original
                .file_stem()
                .and_then(|s| s.to_str())
                .unwrap_or("image");
            let alt_escaped = escape_html(alt);
            let avif: Vec<_> = asset
                .outputs
                .iter()
                .filter(|o| o.format == Format::Avif)
                .collect();
            let webp: Vec<_> = asset
                .outputs
                .iter()
                .filter(|o| o.format == Format::Webp)
                .collect();

            let _ = writeln!(html, "<picture>");
            if !avif.is_empty() {
                let srcset = format_srcset(&avif, &cfg.output_dir);
                let _ = writeln!(html, "  <source type=\"image/avif\" srcset=\"{srcset}\">");
            }
            if !webp.is_empty() {
                let srcset = format_srcset(&webp, &cfg.output_dir);
                let _ = writeln!(html, "  <source type=\"image/webp\" srcset=\"{srcset}\">");
            }
            if let Some(fallback) = webp.last().or_else(|| avif.last()) {
                let name = rel_path_str(&fallback.path, &cfg.output_dir);
                let encoded_src = escape_html(&encode_url_path(&name));
                let _ = writeln!(
                    html,
                    "  <img src=\"{encoded_src}\" alt=\"{alt_escaped}\" loading=\"lazy\" decoding=\"async\">"
                );
            }
            let _ = writeln!(html, "</picture>\n");
        }
        let html_path = cfg.output_dir.join("snippets.html");
        fs::write(&html_path, html).with_context(|| format!("write {}", html_path.display()))?;
    }

    if emit_manifest {
        let entries: Vec<ManifestEntry> = sorted
            .iter()
            .map(|a| ManifestEntry {
                source: rel_path_str(&a.original, &cfg.input_dir),
                original_bytes: a.original_bytes,
                outputs: a
                    .outputs
                    .iter()
                    .map(|o| ManifestFile {
                        file: rel_path_str(&o.path, &cfg.output_dir),
                        width: o.width,
                        format: match o.format {
                            Format::Webp => "webp",
                            Format::Avif => "avif",
                        },
                        bytes: o.bytes,
                    })
                    .collect(),
            })
            .collect();
        let json = serde_json::to_string_pretty(&entries)?;
        let manifest_path = cfg.output_dir.join("manifest.json");
        fs::write(&manifest_path, json)
            .with_context(|| format!("write {}", manifest_path.display()))?;
    }

    Ok(())
}

fn format_srcset(files: &[&crate::pipeline::OutputFile], base: &Path) -> String {
    files
        .iter()
        .map(|f| {
            let rel = rel_path_str(&f.path, base);
            let encoded = escape_html(&encode_url_path(&rel));
            format!("{} {}w", encoded, f.width)
        })
        .collect::<Vec<_>>()
        .join(", ")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_escape_html() {
        assert_eq!(
            escape_html("Hello <World> & \"Friends\" '24"),
            "Hello &lt;World&gt; &amp; &quot;Friends&quot; &#39;24"
        );
    }

    #[test]
    fn test_encode_url_path() {
        assert_eq!(
            encode_url_path("foo bar/baz photo.webp"),
            "foo%20bar/baz%20photo.webp"
        );
        assert_eq!(
            encode_url_path("a#b\"c<d>e.avif"),
            "a%23b%22c%3Cd%3Ee.avif"
        );
    }

    #[test]
    fn test_rel_path_str() {
        assert_eq!(
            rel_path_str(Path::new("/a/b/c.webp"), Path::new("/a/b")),
            "c.webp"
        );
        assert_eq!(
            rel_path_str(Path::new("/a/b/sub/c.webp"), Path::new("/a/b")),
            "sub/c.webp"
        );
    }
}
